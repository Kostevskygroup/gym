// Стойка кроссовера: стек x…x+30, рельс с роликом со стороны человека (side 1 — человек левее, −1 — правее).
// py — высота ролика; lift — ход блоков; to — куда идёт трос от ролика (точка фигуры), zc — слой троса.
const TW = 30;
function tower(x, py, {side = 1, lift = 16, top = 4, to, zc = 8, foot = 1} = {}) {
  const rx = side > 0 ? x - 10 : x + TW + 4, px = rx + 3, cx = x + TW / 2, fx = side > 0 ? x - 34 : x + TW + 34;
  const s = [
    ...(foot ? [{k: 'line', p: [[fx, 211], [side > 0 ? x + TW + 6 : x - 6, 211]], w: 5, z: -1}] : []),
    {k: 'rect', x: rx, y: top + 8, w: 6, h: 207 - top - 8, c: 'steel', z: -1},
    {k: 'stack', x, top, w: TW, lift, z: -1, cable: {to: [px, py], via: [[cx, top + 10], [px, top + 10]]}},
    {k: 'rect', x: px - 7, y: py - 7, w: 14, h: 14, c: 'dark', z: -1},
    {k: 'pulley', x: px, y: py, z: -1},
  ];
  if (to) s.push({k: 'cable', from: [px, py], to, z: zc, handle: false});
  return s;
}
// Канат в кулаке: прядь от кисти к узлу, узел — к тросу.
const rope = (d = [4, 12], at = 'hn') => [
  {k: 'bar', a: {p: at, d: [-d[0] * 0.4, -d[1] * 0.4]}, b: {p: at, d}, ext: 0, plates: false, z: 8},
  {k: 'handle', at: {p: at, d}, r: 3, z: 8},
];
const KNOT = d => ({p: 'hn', d});
const dh = (at = 'hn', z = 8) => ({k: 'handle', at, z});

// Разножка в профиль: таз в at, щиколотки на полу (ближняя впереди, дальняя сзади на носке).
const split = (at, front, back, t = 4) => ({at, t, ik: {l: front, l2: back}, l: [0, 0, 90], l2: [0, 0, 122]});

