// ---- скамья (img/bench.jpg), как в bench.js: верх подушки by (обычно BY); спинка ang° от горизонта, dir 1 — поднимается вправо ----
const BY = 170;
const onBack = (hx, ang, dir, d, off = 0, by = BY) => {
  const c = Math.cos(rad(ang)), s = Math.sin(rad(ang));
  return [hx + dir * (d * c - 4.5 * s) - dir * s * off, by + 4.5 - d * s - 4.5 * c - c * off];
};
function bench(hx, ang = 0, dir = -1, z = 3, by = BY) {
  const seat = 34, len = 84, sx = dir < 0 ? hx + 2 : hx - 2 - seat, fx = sx + seat / 2, rx = hx + dir * (len - 12);
  const prop = ang ? onBack(hx, ang, dir, len * 0.5, -9, by) : [rx, by + 8];
  return [
    {k: 'line', p: [[fx, by + 8], [fx, 205], [rx, 205]], w: 6, z},
    {k: 'line', p: [[hx + dir * 24, 205], prop], w: 5, z},
    {k: 'handle', at: [fx, 208], r: 5, z}, {k: 'handle', at: [rx, 208], r: 5, z},
    {k: 'pad', x: dir < 0 ? hx - len : hx, y: by, w: len, h: 9, rot: -dir * ang, ox: hx, oy: by + 4.5, z},
    {k: 'pad', x: sx, y: by, w: seat, h: 9, z},
  ];
}
