// икры: нижний край платформы — под подушечкой стопы, пятка свисает
const TOE = {p: 'to', d: [8, -26]};

// Валик в профиль: светлый обод, мягкая подушка, торец-втулка.
const pad = (at, r, z, arm) => [{k: 'db', at, r: r + 1.6, z}, {k: 'roller', at, r, arm, z}, {k: 'handle', at, r: 2.8, z}];

// ---- Разгибание / сгибание ног сидя: ось рычага напротив колена, стек впереди-сбоку ----
const HIP = [124, 160], KNEE = [168, 160];
const SIT = {at: HIP, t: -10, hd: 6, ik: {a: [136, 167]}};
// lift — ход блоков с движением; hold — блоки подняты и стоят (удержание)
const chair = (lift = 20, hold = 0) => [
  {k: 'rect', x: 100, y: 209, w: 160, h: 5, c: 'steel', z: -1},
  ...(hold ? heldStack(222, 56, hold) : [{k: 'stack', x: 222, top: 56, lift, z: -1}]),
  {k: 'line', p: [KNEE, [224, 136]], w: 8, z: -1},
  {k: 'seat', x: 107, y: 172, w: 46, back: {ang: 78, len: 82}},
  {k: 'line', p: [[118, 170], [142, 168]], w: 4, z: 6},
  {k: 'handle', at: KNEE, r: 3.5, z: 8},
];
// разгибание: валик на передней стороне голени над стопой. Валик несёт носок спрятанной за голенью дальней стопы
// (две ноги) или ближний носок, взятый на себя (одна нога): так валик поворачивается вместе с голенью.
const extS = (lift, at = 'to2', hold = 0) => [...chair(lift, hold), ...pad(at, 9.5, 3, KNEE)];
const ext2 = sh => ({l: [90, sh, sh - 80], l2: [90, sh, sh - 120]});
const ext1 = (sh, l2) => ({l: [90, sh, sh - 120], l2});
// сгибание: верхний валик прижимает бёдра над коленом, нижний — сзади над пяткой
const curlS = (lift, at = 'to2', hold = 0) => [...chair(lift, hold), {k: 'line', p: [[157, 143], [194, 150]], w: 5, z: -1}, ...pad([157, 143], 7, 8),
  ...pad(at, 9.5, 3, KNEE)];
const curl2 = sh => ({l: [90, sh, sh - 90], l2: [90, sh, sh + 120]});
const curl1 = (sh, l2) => ({l: [90, sh, sh - 70], l2});

