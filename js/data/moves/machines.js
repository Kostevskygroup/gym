// Анимация техники: machines — жим ногами (икры, широко, одной ногой), разгибание и сгибание ног сидя (Impulse).
// Формат — js/data/moves.js и js/anim/rig.js.
import {FLOOR_Y} from './kit.js';

// Стек с блоками, поднятыми на up и неподвижными, — для удержаний (обычный stack поднимает блоки вместе с движением).
const heldStack = (x, top, up, w = 34) => [
  {k: 'rect', x: x - 3, y: top, w: 6, h: FLOOR_Y - top, r: 2}, {k: 'rect', x: x + w - 3, y: top, w: 6, h: FLOOR_Y - top, r: 2},
  {k: 'rect', x: x - 3, y: top, w: w + 6, h: 7, r: 2},
  {k: 'line', p: [[x + w / 2 - 6, top + 8], [x + w / 2 - 6, FLOOR_Y - 4]], w: 1.5, c: 'hi'},
  {k: 'line', p: [[x + w / 2 + 6, top + 8], [x + w / 2 + 6, FLOOR_Y - 4]], w: 1.5, c: 'hi'},
  ...Array.from({length: 9}, (_, i) => ({k: 'rect', x: x + 3, y: FLOOR_Y - 10 - (8 - i) * 7 - (i >= 6 ? up : 0), w: w - 6, h: 6, r: 1.5, c: i >= 6 ? 'plateHi' : 'plate'})),
].map(o => ({...o, z: -1}));

// ---- Жим ногами (сцена как BASE legpress): сиденье со спинкой (спина лежит на ней), рычаг от стека держит платформу ----
// поза: таз и рукоять у сиденья как в BASE; ik — щиколотки, рукоять a — всегда
const LP = {at: [112, 150], t: -28, hd: 8};
const lpPose = (ik = {}, rest = {}) => ({...LP, ...rest, ik: {a: [122, 156], ...ik}});
const LP_FIT = [[278, 60]];
const lp = (plat, lift = 22) => [
  {k: 'rail', p: [[108, 210], [262, 210]], w: 6, z: -1},
  {k: 'stack', x: 232, top: 64, lift, z: -1},
  {k: 'lever', from: [232, 138], to: plat, w: 6, z: -1},
  {k: 'seat', x: 104, y: 160, w: 56, back: {ang: 62, len: 74}},
  {k: 'handle', at: 'hn', z: 8},
  {k: 'plat', at: plat, ang: 6, w: 78, z: 8},
];
// икры: нижний край платформы — под подушечкой стопы, пятка свисает
const TOE = {p: 'to', d: [9, -30]};

// Валик в профиль: светлый обод, мягкая подушка, торец-втулка.
const pad = (at, r, z, arm) => [{k: 'db', at, r: r + 1.6, z}, {k: 'roller', at, r, arm, z}, {k: 'handle', at, r: 2.8, z}];

// ---- Разгибание / сгибание ног сидя: ось рычага напротив колена, стек впереди-сбоку ----
const HIP = [124, 152], KNEE = [168, 152];
const SIT = {at: HIP, t: -10, hd: 6, ik: {a: [136, 159]}};
// lift — ход блоков с движением; hold — блоки подняты и стоят (удержание)
const chair = (lift = 20, hold = 0) => [
  {k: 'rect', x: 100, y: 209, w: 160, h: 5, c: 'steel', z: -1},
  ...(hold ? heldStack(222, 56, hold) : [{k: 'stack', x: 222, top: 56, lift, z: -1}]),
  {k: 'line', p: [KNEE, [224, 128]], w: 8, z: -1},
  {k: 'seat', x: 107, y: 164, w: 46, back: {ang: 78, len: 82}},
  {k: 'line', p: [[118, 162], [142, 160]], w: 4, z: 6},
  {k: 'handle', at: KNEE, r: 3.5, z: 8},
];
// разгибание: валик на передней стороне голени над стопой. Валик несёт носок спрятанной за голенью дальней стопы
// (две ноги) или ближний носок, взятый на себя (одна нога): так валик поворачивается вместе с голенью.
const extS = (lift, at = 'to2', hold = 0) => [...chair(lift, hold), ...pad(at, 9.5, 3, KNEE)];
const ext2 = sh => ({l: [90, sh, sh - 80], l2: [90, sh, sh - 120]});
const ext1 = (sh, l2) => ({l: [90, sh, sh - 105], l2});
// сгибание: верхний валик прижимает бёдра над коленом, нижний — сзади над пяткой
const curlS = (lift, at = 'to2', hold = 0) => [...chair(lift, hold), {k: 'line', p: [[157, 135], [194, 142]], w: 5, z: -1}, ...pad([157, 135], 7, 8),
  ...pad(at, 9.5, 3, KNEE)];
const curl2 = sh => ({l: [90, sh, sh - 105], l2: [90, sh, sh + 120]});
const curl1 = (sh, l2) => ({l: [90, sh, sh - 100], l2});

