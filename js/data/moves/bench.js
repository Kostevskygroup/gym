// Анимация техники: регулируемая скамья (img/bench.jpg) — жимы, тяги, разводки, бицепс/трицепс, пресс.
// Формат — js/data/moves.js и js/anim/rig.js. Верх подушки — y = 170; лёжа центр корпуса ~14 над подушкой.
import {ANKLE_Y} from './kit.js';

const BY = 170, rad = d => d * Math.PI / 180;

// Точка на верхней стороне спинки: d — от шарнира hx вдоль спинки, off — по нормали над подушкой.
// dir: −1 — спинка поднимается влево (лёжа спиной, голова слева), 1 — вправо (лёжа грудью, лицом вправо).
const onBack = (hx, ang, dir, d, off = 0) => {
  const c = Math.cos(rad(ang)), s = Math.sin(rad(ang));
  return [hx + dir * (d * c - 4.5 * s) - dir * s * off, BY + 4.5 - d * s - 4.5 * c - c * off];
};

// Скамья в профиль: сиденье по одну сторону шарнира, спинка (ang° от горизонта) — по другую.
// Рама как на фото: стойка под сиденьем, балка к задней опоре, опоры-трубы на полу, упор спинки.
function bench(hx, ang = 0, dir = -1, z = 3) {
  const seat = 34, len = 84, sx = dir < 0 ? hx + 2 : hx - 2 - seat, fx = sx + seat / 2, rx = hx + dir * (len - 12);
  const prop = ang ? onBack(hx, ang, dir, len * 0.5, -9) : [rx, BY + 8];
  return [
    {k: 'line', p: [[fx, BY + 8], [fx, 205], [rx, 205]], w: 6, z},
    {k: 'line', p: [[hx + dir * 24, 205], prop], w: 5, z},
    {k: 'handle', at: [fx, 208], r: 5, z}, {k: 'handle', at: [rx, 208], r: 5, z},
    {k: 'pad', x: dir < 0 ? hx - len : hx, y: BY, w: len, h: 9, rot: -dir * ang, ox: hx, oy: BY + 4.5, z},
    {k: 'pad', x: sx, y: BY, w: seat, h: 9, z},
  ];
}
