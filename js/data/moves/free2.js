const r1 = v => Math.round(v * 10) / 10;
// Шаг: щиколотка идёт по дуге от A к B, выгнутой вверх на lift (стопа отрывается и ставится снова). → [ik старта, ik финиша]
function step(A, B, lift = 8) {
  const dx = B[0] - A[0], dy = B[1] - A[1], L = Math.hypot(dx, dy), r = (L * L / 4 + lift * lift) / (2 * lift);
  const s = dx >= 0 ? 1 : -1, c = [r1((A[0] + B[0]) / 2 - s * dy / L * (r - lift)), r1((A[1] + B[1]) / 2 + s * dx / L * (r - lift))];
  const ang = p => r1(Math.atan2(p[0] - c[0], c[1] - p[1]) * 180 / Math.PI);
  return [{c, r: r1(r), ang: ang(A)}, {c, r: r1(r), ang: ang(B)}];
}

