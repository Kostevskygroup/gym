// Верх подушек — y = 170; лёжа центр корпуса ~14 над подушкой.
import {ANKLE_Y, FLOOR_Y} from './kit.js';

const BY = 170, rad = d => d * Math.PI / 180;

// Скамья в профиль (как на фото и в bench.js): стойка под сиденьем, балка по полу к задней опоре, упор спинки, заглушки.
// x — стык сиденья и спинки; сиденье вправо от x, спинка влево и поднята на ang° (0 — плоско); dir −1 — зеркально.
function bench(x, {ang = 0, y = BY, seat = 40, len = 84, dir = 1, z = 3} = {}) {
  const s = dir, fy = FLOOR_Y - 9, fx = x + s * seat / 2, rx = x - s * (len - 12), px = x - 2 * s;
  // упор: плоско — под конец спинки над задней опорой; поднята — к низу спинки на половине длины
  const L = len * 0.5, c = Math.cos(rad(ang)), n = Math.sin(rad(ang));
  const prop = ang > 5 ? [px - s * (L * c + 5 * n), y + 4 - L * n + 5 * c] : [rx, y + 8];
  return [
    {k: 'line', p: [[fx, y + 8], [fx, fy], [rx, fy]], w: 6, z},
    {k: 'line', p: [[x - s * 24, fy], prop], w: 5, z},
    {k: 'handle', at: [fx, FLOOR_Y - 6], r: 5, z}, {k: 'handle', at: [rx, FLOOR_Y - 6], r: 5, z},
    {k: 'pad', x: s > 0 ? px - len : px, y, w: len, h: 9, rot: s * ang, ox: px, oy: y + 4, z},
    {k: 'pad', x: s > 0 ? x : x - seat, y, w: seat, h: 9, z},
  ];
}
// Та же скамья спереди (сидя на торце лицом к зрителю, как на фото): торец сиденья y на стойке, Т-опора
// с заглушками; top — верх спинки за корпусом (без top — горизонтальная скамья).
const benchF = (cx, y, top) => [
  ...(top ? [{k: 'pad', x: cx - 15, y: top, w: 30, h: y - top + 4, z: -1}] : []),
  {k: 'line', p: [[cx, y + 8], [cx, FLOOR_Y - 9]], w: 7, z: 0},
  {k: 'line', p: [[cx - 30, FLOOR_Y - 6], [cx + 30, FLOOR_Y - 6]], w: 6, z: 0},
  {k: 'handle', at: [cx - 30, FLOOR_Y - 6], r: 5, z: 0}, {k: 'handle', at: [cx + 30, FLOOR_Y - 6], r: 5, z: 0},
  {k: 'pad', x: cx - 17, y, w: 34, h: 10, z: 0},
];
// Точка над верхней стороной спинки, поднятой вправо (dir −1): d — от шарнира x вдоль спинки, off — по нормали.
const onBack = (x, ang, d, off = 0) => {
  const c = Math.cos(rad(ang)), n = Math.sin(rad(ang));
  return [x + 2 + d * c - (4 + off) * n, BY + 4 - d * n - (4 + off) * c];
};

