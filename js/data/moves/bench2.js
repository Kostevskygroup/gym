const BY = 170, rad = d => d * Math.PI / 180;

// Скамья в профиль (как на фото): балка рамы, стойки к опорам-трубам на полу, сиденье и спинка.
// x — стык сиденья и спинки; сиденье вправо от x, спинка влево и поднята на ang° (0 — плоско); dir −1 — зеркально.
function bench(x, {ang = 0, y = BY, seat = 40, len = 84, dir = 1, z = 3} = {}) {
  const s = dir, by = y + 15, fx = x + s * (seat - 6), rx = x - s * (len - 10), px = x - 2 * s;
  const out = [
    {k: 'line', p: [[rx, by], [fx, by]], w: 6, z},
    {k: 'line', p: [[fx - s * 3, by], [fx + s * 3, FLOOR_Y - 5]], w: 5, z},
    {k: 'line', p: [[rx + s * 3, by], [rx - s * 3, FLOOR_Y - 5]], w: 5, z},
    {k: 'handle', at: [fx + s * 3, FLOOR_Y - 5], r: 4.5, z}, {k: 'handle', at: [rx - s * 3, FLOOR_Y - 5], r: 4.5, z},
    {k: 'pad', x: s > 0 ? x : x - seat, y, w: seat, h: 9, z},
    {k: 'pad', x: s > 0 ? px - len : px, y, w: len, h: 9, rot: s * ang, ox: px, oy: y + 4, z},
  ];
  if (ang > 5) { // упор спинки от балки
    const L = len * 0.45, c = Math.cos(rad(ang)), n = Math.sin(rad(ang));
    out.splice(1, 0, {k: 'line', p: [[x - s * 28, by], [px - s * (L * c + 5 * n), y + 4 - L * n + 5 * c]], w: 5, z});
  }
  return out;
}
