// Ширина стека, высота нижнего блока.
const SW = 32, LO = 198;
// Башня кроссовера: колонна с кареткой-роликом (cx, py), стек сбоку (st 1 — справа от колонны, −1 — слева).
// Трос: блоки стека → верхние ролики → каретка. lift — ход блоков, top — верх башни.
function tower(cx, py, st = 1, lift = 16, top = 0) {
  const sx = st > 0 ? cx + 9 : cx - 9 - SW, L = Math.min(cx, sx) - 6, R = Math.max(cx, sx + SW) + 6;
  return [
    {k: 'line', p: [[st > 0 ? cx - 24 : L, 211], [st > 0 ? R : cx + 24, 211]], w: 6, z: -1},
    {k: 'rect', x: L, y: top - 5, w: R - L, h: 8, z: -1},
    {k: 'rect', x: cx - 4, y: top, w: 8, h: FLOOR_Y - top - 3, c: 'hi', z: -1},
    {k: 'rect', x: cx - 6, y: py - 9, w: 12, h: 18, c: 'dark', z: -1},
    {k: 'stack', x: sx, top, w: SW, lift, z: -1, cable: {to: [cx, py], via: [[sx + SW / 2, top + 11], [cx, top + 11]]}},
    {k: 'pulley', x: cx, y: py, z: -1},
  ];
}
// Трос от каретки к точке фигуры; D-рукоять и манжета — кружок на конце.
const cab = (cx, py, to = 'hn', z = 8) => ({k: 'cable', from: [cx, py], to, z, handle: false});
const dh = (at = 'hn', z = 8) => ({k: 'handle', at, r: 4.6, z});
const cuff = {k: 'handle', at: 'an', r: 5.2, z: 8};
const MAT = x => ({k: 'mat', x, w: 150, z: -1});

// Турник сверху кроссовера в профиль: башня позади, верхняя балка вперёд, кронштейн вниз к перекладине (bx, by).
// neutral — угловая рукоять (ладони друг к другу) вместо прямой перекладины (в профиль — точка).
function sideBar(bx, by, neutral = false, tx = 84) {
  const top = by - 40, s = [...tower(tx, 150, -1, 0, top)];
  if (neutral) {
    s.push({k: 'line', p: [[tx, top], [bx + 4, top], [bx + 14, top + 8], [bx + 14, by - 8]], w: 6, z: -1},
      {k: 'line', p: [[bx + 14, by - 8], [bx - 12, by + 4]], w: 5, c: 'hi', z: 8});
  } else {
    s.push({k: 'line', p: [[tx, top], [bx, top], [bx + 8, top + 8], [bx + 8, by - 10], [bx, by]], w: 6, z: -1}, dh([bx, by]));
  }
  return s;
}
